import test from 'node:test';
import assert from 'node:assert/strict';
import {MemoryDatabase} from '../src/storage/database.js';
import {createNotebookApp} from '../src/app.js';
import {Catalog} from '../src/services/catalog.js';
import {validateWorkspace} from '../src/core/model.js';
const newApp=async(db=new MemoryDatabase())=>createNotebookApp({database:db,catalog:new Catalog([{broad_field:'Natural Sciences',subject:'Physics',subsection:'Quantum mechanics'},{broad_field:'Natural Sciences',subject:'Physics',subsection:'Electromagnetism'}])});
test('note lifecycle, subsections, revisions and reload',async()=>{
  const db=new MemoryDatabase(),app=await newApp(db);
  const note=app.notes.create({title:'Wavefunctions',subjectName:'Physics',subsectionName:'Quantum mechanics',template:'lecture'});
  assert.equal(app.notes.list().length,1);
  assert.equal(app.store.snapshot.subjects.length,1);
  assert.equal(app.store.snapshot.subjects[0].subsections.length,1);
  assert.ok(note.pages[0].text.includes('Key concepts'));
  app.notes.updatePage(note.id,note.pages[0].id,{text:'Schrödinger equation notes'});
  assert.equal(app.notes.list({query:'Schrödinger'}).length,1);
  const second=app.notes.addPage(note.id,{paper:'grid'});
  assert.equal(app.notes.get(note.id).pages.length,2);
  app.notes.reorderPage(note.id,second.id,0);
  assert.equal(app.notes.get(note.id).pages[0].id,second.id);
  app.notes.deletePage(note.id,second.id);
  assert.equal(app.notes.get(note.id).pages.length,1);
  app.notes.trash(note.id);assert.equal(app.notes.list().length,0);
  assert.equal(app.notes.list({trash:true}).length,1);
  app.notes.restore(note.id);assert.equal(app.notes.list().length,1);
  await app.store.flush();
  const reload=await newApp(db);
  assert.equal(reload.notes.list({query:'Schrödinger'}).length,1);
  validateWorkspace(reload.store.snapshot);
});
test('custom subjects, subsections, tasks and flashcards',async()=>{
  const app=await newApp();
  const n=app.notes.create({subjectName:'Ancient Languages',subsectionName:'Classical Sanskrit',title:'Vocabulary'});
  assert.equal(app.store.snapshot.subjects[0].custom,true);
  app.study.createTask({title:'Finish vocabulary list',dueAt:'2026-11-01T12:00:00.000Z'});
  assert.equal(app.study.listTasks().length,1);
  const card=app.study.addFlashcard({front:'Hello?',back:'Namaste',noteId:n.id});
  app.study.reviewCard(card.id,5);
  assert.equal(app.study.dueCards().length,0);
  app.study.updateTask(app.study.listTasks()[0].id,{done:true});
  assert.equal(app.study.listTasks({showDone:false}).length,0);
});
test('full backup round trip including a PDF blob',async()=>{
  const app=await newApp();
  const n=app.notes.create({subjectName:'Physics',subsectionName:'Electromagnetism'});
  const file=new File([new Uint8Array([37,80,68,70,45,49,46,52])],'lecture.pdf',{type:'application/pdf'});
  const attachment=await app.attachments.attach(n.id,n.pages[0].id,file);
  const backup=await app.backup.export();
  assert.equal(backup.files.length,1);
  const restored=await newApp();
  await restored.backup.restore(backup);
  assert.equal(restored.notes.list().length,1);
  const blob=await restored.attachments.get(attachment.id);
  assert.equal(blob.size,8);
});
test('reject malformed backups',async()=>{
  const app=await newApp();
  await assert.rejects(()=>app.backup.restore({format:'other'}),/Unsupported/);
});
